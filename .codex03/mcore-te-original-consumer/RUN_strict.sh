#!/bin/bash
set -eu
unset PYTHONHOME PYTHONUSERBASE
export PYTHONNOUSERSITE=1 PYTHONDONTWRITEBYTECODE=1 TORCH_DEVICE_BACKEND_AUTOLOAD=0
export OMP_NUM_THREADS=2 MKL_NUM_THREADS=2 OPENBLAS_NUM_THREADS=2
export PYTHONPATH="${MCORE_SOURCE_ROOT:?UNBOUND_SOURCE}:${CANDIDATE_SITE_ROOT:?UNBOUND_TE_SITE}:${ADAPTOR_ROOT:?UNBOUND_ADAPTOR}:${CANN_VENDOR_PYTHONPATH:?UNBOUND_VENDOR_PYTHON}"
for operand in "${D_ROOT:?UNBOUND_NEW_D_ROOT}/iter_0000100" "${E_ROOT:?UNBOUND_NEW_E_ROOT}/iter_0000100"; do
 test -d "$operand"
 test -z "$(find "$operand" -mindepth 1 ! -type f ! -type d -print -quit)"
 find "$operand" -type f -print0 | sort -z | xargs -0 -r sha256sum
done
exec "${PYTHON:?UNBOUND_SELECTED_INTERPRETER}" "${COMPARE_OBSERVER:?UNBOUND_ORIGINAL_COMPARE_OBSERVER}" "${STRICT_READER:?UNBOUND_ORIGINAL_STRICT_READER}" --input "$D_ROOT/iter_0000100" --loaded-snapshot "$E_ROOT/iter_0000100" --mcore-root "$MCORE_SOURCE_ROOT" --expected-iteration 100 --output "${STRICT_OUTPUT:?UNBOUND_NEW_STRICT_OUTPUT}"
